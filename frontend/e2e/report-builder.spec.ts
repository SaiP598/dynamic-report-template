import { test, expect } from '@playwright/test';

test('edit, persist, download saved settings, recover from failures, and restore', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('dialog', dialog => dialog.accept());
  await page.goto('/');
  await expect(page.locator('.section-card')).toHaveCount(7);
  const save = page.getByRole('button', { name: 'Save template', exact: true });
  await expect(save).toBeDisabled();
  await page.locator('.section-card input').first().fill('Regression heading');
  const moveDown = page.getByRole('button', { name: 'Move Regression heading down', exact: true });
  await moveDown.focus();
  await page.keyboard.press('Enter');
  await expect(page.locator('.section-card input').nth(1)).toHaveValue('Regression heading');
  const ids = await page.locator('.section-card input').evaluateAll(nodes => nodes.map(n => n.id));
  const source = await page.locator('.drag-grip').first().boundingBox();
  const target = await page.locator('.section-card').nth(2).boundingBox();
  if (!source || !target) throw new Error('Missing drag geometry');
  await page.mouse.move(source.x + 5, source.y + 5);
  await page.mouse.down();
  await page.mouse.move(source.x + 5, source.y + 20, { steps: 5 });
  await page.mouse.move(target.x + 40, target.y + target.height - 10, { steps: 25 });
  await page.mouse.up();
  await expect(page.locator('.cdk-drag-preview')).toHaveCount(0);
  await expect(page.locator('.cdk-drag-placeholder')).toHaveCount(0);
  await expect(page.locator('.section-card input').first()).not.toHaveAttribute('id', ids[0]);
  const reorderedIds = await page.locator('.section-card input').evaluateAll(nodes => nodes.map(n => n.id));
  expect([...reorderedIds].sort()).toEqual([...ids].sort());
  await page.locator('#header-text').fill('Saved regression header');
  await page.locator('#header-size').fill('20');
  await page.locator('#header-alignment').selectOption('right');
  await page.locator('#header-color').fill('#126644');
  await page.locator('fieldset').first().getByLabel('Italic', { exact: true }).check();
  await page.locator('#footer-text').fill('Saved regression footer');
  await save.click();
  await expect(page.getByText('Template saved. Your changes will be available when you reopen the editor.')).toBeVisible();
  await page.reload();
  await expect(page.locator('#header-text')).toHaveValue('Saved regression header');
  await expect(page.locator('#header-size')).toHaveValue('20');
  await expect(page.locator('#header-color')).toHaveValue('#126644');
  expect(await page.locator('.section-card input').evaluateAll(nodes => nodes.map(n => n.id))).toEqual(reorderedIds);
  await expect(page.locator('fieldset').first().getByLabel('Italic', { exact: true })).toBeChecked();
  await page.locator('#header-text').fill('UNSAVED_BROWSER_DRAFT');
  const pdfResponse = page.waitForResponse(r => r.url().endsWith('/api/reports'));
  const downloaded = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download PDF', exact: true }).click();
  const response = await pdfResponse;
  expect(response.status()).toBe(200);
  expect(response.headers()['content-type']).toContain('application/pdf');
  expect(response.headers()['x-template-revision']).toBe('1');
  expect((await downloaded).suggestedFilename()).toBe('dynamic-report.pdf');
  // The download leaves the unsaved draft untouched; backend tests inspect PDF text.
  await expect(page.locator('#header-text')).toHaveValue('UNSAVED_BROWSER_DRAFT');
  await page.route('**/api/reports', route => route.fulfill({ status: 503, body: '{}' }));
  await page.getByRole('button', { name: 'Download PDF', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Could not generate the report');
  await page.unroute('**/api/reports');
  const retriedDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download PDF', exact: true }).click();
  await retriedDownload;
  await page.route('**/api/templates/current', route => route.request().method() === 'PUT'
    ? route.fulfill({ status: 503, body: '{}' }) : route.continue());
  await save.click();
  await expect(page.getByRole('alert')).toContainText('Your edits are still here');
  await expect(page.locator('#header-text')).toHaveValue('UNSAVED_BROWSER_DRAFT');
  await page.unroute('**/api/templates/current');
  await save.click();
  await expect(page.getByText('Template saved. Your changes will be available when you reopen the editor.')).toBeVisible();
  await page.locator('#footer-text').fill('Unsaved footer after retry');
  await page.locator('#header-size').fill('99');
  await expect(save).toBeDisabled();
  await page.locator('#header-size').fill('20');
  await page.getByRole('button', { name: 'Restore default', exact: true }).click();
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(page.locator('#header-text')).toHaveValue('UNSAVED_BROWSER_DRAFT');
  await page.getByRole('button', { name: 'Restore default', exact: true }).click();
  await page.route('**/api/templates/current/restore', route => route.fulfill({ status: 503, body: '{}' }));
  await page.getByRole('button', { name: 'Confirm restore', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Could not restore the default');
  await expect(page.locator('#footer-text')).toHaveValue('Unsaved footer after retry');
  await page.unroute('**/api/templates/current/restore');
  await page.getByRole('button', { name: 'Confirm restore', exact: true }).click();
  await expect(page.getByText('Default template restored and saved.')).toBeVisible();
  await page.reload();
  await expect(save).toBeDisabled();
  await expect(page.locator('.section-card input').first()).toHaveValue('Current Patient Medications');
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});

test('load failure is recoverable', async ({ page }) => {
  await page.route('**/api/templates/current', route => route.fulfill({ status: 503, body: '{}' }));
  await page.goto('/');
  await expect(page.getByRole('alert')).toContainText('could not load');
  await page.unroute('**/api/templates/current');
  await page.getByRole('button', { name: 'Retry loading' }).click();
  await expect(page.locator('.section-card')).toHaveCount(7);
});
